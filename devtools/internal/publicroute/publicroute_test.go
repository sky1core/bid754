// Package publicroute is the static half of the public-API routing gate: it
// enforces, outside the generation path (portprovenance-style: hand-written,
// exhaustive, unused entries fail), that the checked-in public-API routing
// inventory stays faithful to the source and that every public wrapper actually
// routes through the Go mechanical port.
//
// Four checks, each exhaustive:
//
//  1. Census re-validation: the symbol set recorded in the checked-in
//     public_api_routing_inventory.json equals the exported func/method/var set of
//     the module-root package `bid754` read independently from source (both
//     directions). A hand commit that adds or removes a public symbol without
//     regenerating the inventory, or an inconsistent inventory edit, fails here.
//
//  2. Inventory->shim agreement: for every mapped symbol, the FULL set of port
//     functions reachable from the wrapper's body through the package-level Go
//     plumbing (method -> ...Port helper -> bidgo.Fn) is compared exactly. A
//     simple wrapper's reachable set must be exactly the singleton of the port
//     function the inventory records; a composed wrapper (mode dispatch, predicate
//     composition, checked constructors) must match its pinned complete
//     callee set exactly AND the inventory's representative function is pinned per
//     entry, so changing either the shim or the inventory representative fails.
//
//  3. Chain cross-check (FM9 connection guarantee): every port function any
//     mapped wrapper actually reaches (the full reachable set, not just the
//     inventory representative) must be exercised by a regular verification
//     domain under its EXACT Go name: the goport readtest dispatch inventory's
//     go_function set, or the bidgo functions the generated FFI bit-compare
//     artifact literally calls. A reachable function absent from both must
//     either be machine-proven variant-equivalent to a surface sibling by
//     bidgo body structure (the base calls the surface WithFlags sibling, the
//     surface sibling calls the base, or both delegate to the same single
//     value-path function), or be covered by the dedicated flagless-variant
//     equivalence gate. There is no silent name normalization: variant
//     equivalence is proven, not assumed.
//
//  4. FM7 native-path check: no file on the public runtime path (a
//     non-test root file that participates in the default build, i.e. does not
//     require the bid754_native tag) may `import "C"` or reference a
//     native-only symbol. The set of cgo files is pinned exhaustively so a new
//     cgo file must justify itself and stay gated out of the public build. As a
//     strict corroborator this check also loads the typed public build, so
//     a public file that references a native-only symbol (undefined in Config A)
//     fails the type-check, not just the AST name scan.
//
// Resolution boundary (what is semantic vs syntactic):
//
//   - Checks 2 and 3 resolve identifiers and calls by go/types OBJECT IDENTITY
//     (typedload_test.go): reachability edge-following, bidgo-call detection,
//     bidgo body-callee resolution, and the variant-equivalence value flow all
//     key off resolved *types.Func objects over the Config A public build and
//     the bidgo package type-checked from source. Import aliases, unrelated
//     package aliases, package-function-name shadowing, and same-named locals
//     in bidgo bodies therefore cannot pass. The resolver identity corpus
//     (resolver_identity_corpus_test.go) pins this closure.
//   - Checks 1 and 4 stay go/ast on purpose: census is declaration ENUMERATION
//     (identifier resolution is not involved, and it must union symbols across
//     build-tag variants go/types checks one configuration at a time); the cgo
//     cgo and native-only-symbol checks operate on files that `import "C"`, which
//     go/types cannot type-check from source.
//   - Bounded structural residuals (reported as residual, not "verified by
//     types"): the FFI-surface extraction stays AST and is bounded by
//     verify-generated byte pins; the flagless-variant equivalence gate pair
//     extraction reads a bidgo external test package and stays AST; a value
//     passed through unsafe.Pointer bit reinterpretation has no call/method
//     object and is opaque to both AST and go/types, the same accepted residual
//     the value-flow tracker documents.
