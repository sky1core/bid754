// sourceExportedSymbols reads the exported functions, methods, and package
// variables of the module-root package `bid754` directly from source, mirroring
// the generator's loadPublicAPISigs population (all non-test files, generated
// included, build tags ignored so native and stub variants collapse to one
// entry). Reimplemented here independently so the comparison against the inventory
// is a real cross-check, not a shared-code tautology.
func sourceExportedSymbols(t *testing.T) map[string]string {
	t.Helper()
	symbols := map[string]string{}
	for _, name := range rootGoFiles(t) {
		file := parseRootFile(t, name)
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if !d.Name.IsExported() {
					continue
				}
				if d.Recv == nil {
					symbols[d.Name.Name] = "func"
					continue
				}
				recv := receiverTypeName(d.Recv)
				if recv == "" {
					t.Fatalf("%s: cannot resolve receiver type for method %q", name, d.Name.Name)
				}
				symbols[recv+"."+d.Name.Name] = "method"
			case *ast.GenDecl:
				if d.Tok != token.VAR {
					continue
				}
				for _, spec := range d.Specs {
					vs, ok := spec.(*ast.ValueSpec)
					if !ok {
						continue
					}
					for _, ident := range vs.Names {
						if ident.IsExported() {
							symbols[ident.Name] = "var"
						}
					}
				}
			}
		}
	}
	if len(symbols) == 0 {
		t.Fatal("no exported public symbols found in source; wrong path?")
	}
	return symbols
}

func TestPublicAPIInventoryMatchesSourceCensus(t *testing.T) {
	inventory := loadInventory(t)
	source := sourceExportedSymbols(t)

	inventorySymbols := map[string]string{}
	for _, row := range inventory.Symbols {
		if _, dup := inventorySymbols[row.Symbol]; dup {
			t.Errorf("inventory lists symbol %q more than once", row.Symbol)
		}
		inventorySymbols[row.Symbol] = row.Kind
	}

	// Source symbols missing from the inventory require regeneration.
	for sym, kind := range source {
		inventoryKind, ok := inventorySymbols[sym]
		if !ok {
			t.Errorf("exported source symbol %q (%s) is absent from the routing inventory; regenerate public_api_routing_inventory.json", sym, kind)
			continue
		}
		if inventoryKind != kind {
			t.Errorf("symbol %q kind mismatch: source=%s inventory=%s", sym, kind, inventoryKind)
		}
	}
	// Inventory symbols missing from source also require regeneration.
	for sym, kind := range inventorySymbols {
		if _, ok := source[sym]; !ok {
			t.Errorf("routing inventory lists symbol %q (%s) that no longer exists in source; regenerate public_api_routing_inventory.json", sym, kind)
		}
	}
	if inventory.Total != len(inventorySymbols) {
		t.Errorf("inventory total field = %d but it lists %d distinct symbols", inventory.Total, len(inventorySymbols))
	}
}

