// cgoNativeFiles pins the non-test root files that `import "C"`. Every one must
// be gated behind bid754_native (excluded from the public runtime build) and
// carry a concrete reason. Exhaustive: a new cgo file (or a removed one)
// fails until this list is updated, and a public-runtime file that imports C
// fails both this list and the no-C rule below.
var cgoNativeFiles = map[string]string{
	"c_bid_benchmark_native.go":                  "bid754_native-gated cgo benchmark harness comparing the Go port against native Intel BID; excluded from the public runtime build",
	"dectest_native.go":                          "generated bid754_native-gated native decTest reference oracle; excluded from the public runtime build",
	"generated_readtest_dispatch_native.go":      "generated bid754_native-gated native readtest dispatch oracle; excluded from the public runtime build",
	"generated_ffi_bitcompare_native.go":         "generated bid754_native-gated native FFI bit-compare oracle; excluded from the public runtime build",
	"generated_decnumber_differential_native.go": "generated bid754_native+bid754_decnumber_diff-gated decNumber 3.68 differential-oracle shim (test files cannot carry cgo preambles); excluded from the public runtime build",
}

func fileImportsC(file *ast.File) bool {
	for _, imp := range file.Imports {
		if imp.Path != nil && imp.Path.Value == `"C"` {
			return true
		}
	}
	return false
}

// topLevelDeclNames returns the package-level func (receiver-less), type, var,
// and const identifier names declared in file.
func topLevelDeclNames(file *ast.File) []string {
	var names []string
	for _, decl := range file.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if d.Recv == nil {
				names = append(names, d.Name.Name)
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					names = append(names, s.Name.Name)
				case *ast.ValueSpec:
					for _, ident := range s.Names {
						names = append(names, ident.Name)
					}
				}
			}
		}
	}
	return names
}

func TestPublicBuildFilesRouteThroughPortWithoutCgo(t *testing.T) {
	// Strict cross-check: the Config A public build must type-check with
	// zero errors. A public-runtime file that references a native-only symbol is
	// undefined in Config A, so the typed load fails here in addition to the AST
	// name scan below (which keeps a precise per-symbol diagnostic). The load is
	// cached (sync.Once), so this is shared with checks 2 and 3.
	loadTypedPublicBuild(t)

	type parsed struct {
		name        string
		file        *ast.File
		native      bool
		importsC    bool
		topLevelDef []string
	}
	var files []parsed
	for _, name := range rootGoFiles(t) {
		file := parseRootFile(t, name)
		files = append(files, parsed{
			name:        name,
			file:        file,
			native:      requiresNative(fileBuildConstraint(t, file)),
			importsC:    fileImportsC(file),
			topLevelDef: topLevelDeclNames(file),
		})
	}

	// Native-only symbols: package-level names declared in bid754_native-gated
	// files that no public-runtime file also declares (so they are not the dual
	// build/stub symbols). A public-runtime file must not reference them.
	nativeDecls := map[string]bool{}
	publicDecls := map[string]bool{}
	for _, f := range files {
		target := publicDecls
		if f.native {
			target = nativeDecls
		}
		for _, n := range f.topLevelDef {
			target[n] = true
		}
	}
	nativeOnly := map[string]bool{}
	for n := range nativeDecls {
		if !publicDecls[n] {
			nativeOnly[n] = true
		}
	}

	// Exhaustive check over the cgo file list.
	for name, reason := range cgoNativeFiles {
		if strings.TrimSpace(reason) == "" {
			t.Errorf("cgoNativeFiles[%q] has an empty reason", name)
		}
		var f *parsed
		for i := range files {
			if files[i].name == name {
				f = &files[i]
				break
			}
		}
		if f == nil {
			t.Errorf("cgoNativeFiles entry %q is not a non-test root file; remove the stale entry", name)
			continue
		}
		if !f.importsC {
			t.Errorf("cgoNativeFiles entry %q no longer imports \"C\"; remove the stale entry", name)
		}
		if !f.native {
			t.Errorf("cgoNativeFiles entry %q imports \"C\" but is not gated behind bid754_native; it would drag cgo onto the public runtime path", name)
		}
	}

	for _, f := range files {
		if f.importsC {
			if _, ok := cgoNativeFiles[f.name]; !ok {
				t.Errorf("root file %q imports \"C\" but is not in the complete cgoNativeFiles list; public runtime files must route through the Go mechanical port", f.name)
			}
			continue
		}
		if f.native {
			continue // native oracle path, not the public runtime path
		}
		// Public-runtime file: it must not reference a native-only symbol.
		ast.Inspect(f.file, func(n ast.Node) bool {
			ident, ok := n.(*ast.Ident)
			if !ok {
				return true
			}
			if nativeOnly[ident.Name] {
				t.Errorf("public-runtime file %q references native-only symbol %q; the public path must route through the Go mechanical port, not the bid754_native oracle", f.name, ident.Name)
			}
			return true
		})
	}
}
