// goportSurface returns the exact Go function names the goport readtest gate
// dispatches (the go_function column of the checked-in dispatch inventory).
func goportSurface(t *testing.T) map[string]bool {
	t.Helper()
	raw, err := os.ReadFile(goportInventoryRel)
	if err != nil {
		t.Fatalf("read %s: %v", goportInventoryRel, err)
	}
	var doc struct {
		Functions []struct {
			GoFunction string `json:"go_function"`
			Status     string `json:"status"`
		} `json:"functions"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("unmarshal %s: %v", goportInventoryRel, err)
	}
	set := map[string]bool{}
	for _, fn := range doc.Functions {
		if fn.Status == "dispatched" && fn.GoFunction != "" {
			set[fn.GoFunction] = true
		}
	}
	if len(set) == 0 {
		t.Fatalf("%s has no dispatched functions", goportInventoryRel)
	}
	return set
}

// ffiSurface returns the exact bidgo function names the generated FFI
// bit-compare artifact literally calls. This is the FFI domain's Go-side
// surface (the artifact compares each of these calls bit-exactly against the
// native Intel function), extracted from the checked-in generated file that
// verify-generated byte-pins. The C-spelled spec file names under
// generated/testspec/ffi are NOT used: matching them would need a name
// normalization that silently conflates variants.
func ffiSurface(t *testing.T) map[string]bool {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, ffiBitcompareRel, nil, parser.SkipObjectResolution)
	if err != nil {
		t.Fatalf("parse %s: %v", ffiBitcompareRel, err)
	}
	set := map[string]bool{}
	ast.Inspect(file, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		if sel, ok := call.Fun.(*ast.SelectorExpr); ok {
			if x, ok := sel.X.(*ast.Ident); ok && x.Name == "bidgo" {
				set[sel.Sel.Name] = true
			}
		}
		return true
	})
	if len(set) == 0 {
		t.Fatalf("%s calls no bidgo functions; the FFI surface extraction lost its subject", ffiBitcompareRel)
	}
	return set
}

// equivalenceGatePinnedPairs parses the hand-written bidgo flagless-variant
// equivalence gate and returns the flagless function names it pins: an entry
// of the gate's exhaustive target list counts only if the composite-literal
// element references BOTH the flagless identifier and its WithFlags sibling
// identifier (the actual function values the gate executes - a name string
// alone proves nothing).
func equivalenceGatePinnedPairs(t *testing.T) map[string]bool {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, equivalenceGateFileRel, nil, parser.SkipObjectResolution)
	if err != nil {
		t.Fatalf("parse equivalence gate %s: %v", equivalenceGateFileRel, err)
	}
	targetVars := map[string]bool{}
	for _, name := range equivalenceGateTargetVarNames {
		targetVars[name] = true
	}
	pinned := map[string]bool{}
	found := map[string]bool{}
	ast.Inspect(file, func(n ast.Node) bool {
		vs, ok := n.(*ast.ValueSpec)
		if !ok {
			return true
		}
		for i, name := range vs.Names {
			if !targetVars[name.Name] || i >= len(vs.Values) {
				continue
			}
			found[name.Name] = true
			outer, ok := vs.Values[i].(*ast.CompositeLit)
			if !ok {
				continue
			}
			for _, elt := range outer.Elts {
				entry, ok := elt.(*ast.CompositeLit)
				if !ok {
					continue
				}
				idents := map[string]bool{}
				ast.Inspect(entry, func(m ast.Node) bool {
					if id, ok := m.(*ast.Ident); ok {
						idents[id.Name] = true
					}
					return true
				})
				for id := range idents {
					if !strings.HasSuffix(id, "WithFlags") && idents[id+"WithFlags"] {
						pinned[id] = true
					}
				}
			}
		}
		return true
	})
	for _, name := range equivalenceGateTargetVarNames {
		if !found[name] {
			t.Errorf("equivalence gate %s does not declare %s; the sibling-equivalence coverage lost its anchor", equivalenceGateFileRel, name)
		}
	}
	return pinned
}

func TestPublicAPIPortFunctionsAreVerifiedByADomain(t *testing.T) {
	inventory := loadInventory(t)
	tb := loadTypedPublicBuild(t)
	rootRes := tb.rootResolver()
	bidgoRes := tb.bidgoResolver()
	goport := goportSurface(t)
	ffi := ffiSurface(t)

	covered := func(fn string) bool { return goport[fn] || ffi[fn] }

	// Full reachable set per mapped symbol; the chain input is the union of
	// everything the wrappers actually route through, plus every inventory
	// representative (the parity contract functions must be verified too).
	targets := map[string]bool{}
	for _, row := range inventory.Symbols {
		if row.Status != "mapped" {
			continue
		}
		var start *ast.FuncDecl
		if row.Kind == "method" {
			start = tb.rootMethodsByName[row.Symbol]
		} else {
			start = tb.rootFuncsByName[row.Symbol]
		}
		if start == nil {
			t.Errorf("mapped symbol %q not found among public-build declarations", row.Symbol)
			continue
		}
		r := withoutRepresentationPlumbing(rootRes.reachablePortFuncs(start), map[string]bool{})
		for fn := range r {
			targets[fn] = true
		}
		if row.BidgoFunction != "" {
			targets[row.BidgoFunction] = true
		}
	}
	if len(targets) == 0 {
		t.Fatal("no reachable port functions found; the cross-check lost its subject")
	}

	gatePinned := equivalenceGatePinnedPairs(t)

	usedSiblingEquivalence := map[string]bool{}
	equivalenceProven := map[string]bool{}
	for _, fn := range sortedSet(targets) {
		if covered(fn) {
			continue
		}
		if how, ok := bidgoRes.proveVariantEquivalence(fn, covered); ok {
			equivalenceProven[fn] = true
			if _, hasEntry := siblingEquivalenceCoveredPortFunctions[fn]; hasEntry {
				t.Errorf("siblingEquivalenceCoveredPortFunctions entry %q is AST-equivalence-provable (%s); the runtime gate entry is redundant, remove it", fn, how)
			}
			t.Logf("port function %q covered by variant equivalence: %s", fn, how)
			continue
		}
		if reason, ok := siblingEquivalenceCoveredPortFunctions[fn]; ok {
			usedSiblingEquivalence[fn] = true
			if strings.TrimSpace(reason) == "" {
				t.Errorf("siblingEquivalenceCoveredPortFunctions[%q] has an empty reason", fn)
			}
			sibling := fn + "WithFlags"
			if !covered(sibling) {
				t.Errorf("siblingEquivalenceCoveredPortFunctions[%q]: sibling %q is not on the goport/FFI surface, so the equivalence gate has no oracle-verified side; the coverage claim is broken", fn, sibling)
			}
			if !gatePinned[fn] {
				t.Errorf("siblingEquivalenceCoveredPortFunctions[%q]: the flagless-variant equivalence gate (%s) does not pin the {%s, %s} pair; the gate does not cover this function", fn, equivalenceGateFileRel, fn, sibling)
			}
			continue
		}
		t.Errorf("reachable port function %q is not exercised by the goport readtest or FFI surface, has no AST-provable variant equivalence, and no sibling-equivalence entry -- a wrapper routes through an unverified port function", fn)
	}

	// Reverse completeness check over the gate's target list: the set of pairs the
	// equivalence gate pins must equal the set of sibling-equivalence
	// exceptions exactly. A gate target that no exception needs is stale (it
	// silently widens the runtime gate's claimed purpose), and a missing one
	// already fails the per-entry check above.
	for fn := range gatePinned {
		if _, needed := siblingEquivalenceCoveredPortFunctions[fn]; !needed {
			t.Errorf("equivalence gate pins %q but no siblingEquivalenceCoveredPortFunctions entry needs it; remove the stale gate target or register the exception with its reason", fn)
		}
	}

	for fn := range siblingEquivalenceCoveredPortFunctions {
		if !targets[fn] {
			t.Errorf("siblingEquivalenceCoveredPortFunctions entry %q is not reachable from any mapped wrapper; remove the stale entry", fn)
			continue
		}
		if covered(fn) {
			t.Errorf("siblingEquivalenceCoveredPortFunctions entry %q is now on the goport/FFI surface; remove the stale entry", fn)
			continue
		}
		if equivalenceProven[fn] {
			continue // already reported as redundant above
		}
		if !usedSiblingEquivalence[fn] {
			t.Errorf("siblingEquivalenceCoveredPortFunctions entry %q was not exercised; remove the stale entry", fn)
		}
	}
}

