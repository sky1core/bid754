func fileBuildConstraint(t *testing.T, file *ast.File) constraint.Expr {
	t.Helper()
	for _, cg := range file.Comments {
		if cg.Pos() >= file.Package {
			continue
		}
		for _, c := range cg.List {
			if constraint.IsGoBuild(c.Text) {
				expr, err := constraint.Parse(c.Text)
				if err != nil {
					t.Fatalf("parse build constraint %q: %v", c.Text, err)
				}
				return expr
			}
		}
	}
	return nil
}

// requiresNative reports whether a file is gated behind the bid754_native build
// tag: it is compiled when bid754_native is set (all other tags satisfied) but
// not when bid754_native is off. Such files are the native oracle/benchmark
// path, excluded from the public runtime build. A file with no constraint, or
// one that still compiles with bid754_native off, is on the public runtime path.
func requiresNative(expr constraint.Expr) bool {
	if expr == nil {
		return false
	}
	nativeOff := func(tag string) bool { return tag != "bid754_native" }
	allOn := func(string) bool { return true }
	return !expr.Eval(nativeOff) && expr.Eval(allOn)
}

