type inventoryDoc struct {
	Total    int            `json:"total"`
	Mapped   int            `json:"mapped"`
	Excluded int            `json:"excluded"`
	Symbols  []inventoryRow `json:"symbols"`
}

func loadInventory(t *testing.T) inventoryDoc {
	t.Helper()
	raw, err := os.ReadFile(inventoryPathRel)
	if err != nil {
		t.Fatalf("read %s: %v", inventoryPathRel, err)
	}
	var doc inventoryDoc
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("unmarshal %s: %v", inventoryPathRel, err)
	}
	if len(doc.Symbols) == 0 {
		t.Fatalf("%s contains no symbols", inventoryPathRel)
	}
	return doc
}

// rootGoFiles returns the base names of the non-test .go files directly under
// the bid754-go module root (the public package `bid754`). Generated files are
// included: a generated artifact that exports a symbol widens the public
// surface just like a hand-written one.
func rootGoFiles(t *testing.T) []string {
	t.Helper()
	entries, err := os.ReadDir(publicSrcDirRel)
	if err != nil {
		t.Fatalf("read %s: %v", publicSrcDirRel, err)
	}
	var files []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		files = append(files, name)
	}
	sort.Strings(files)
	if len(files) == 0 {
		t.Fatalf("no non-test .go files found under %s", publicSrcDirRel)
	}
	return files
}

func parseRootFile(t *testing.T, name string) *ast.File {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filepath.Join(publicSrcDirRel, name), nil, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		t.Fatalf("parse %s: %v", name, err)
	}
	return file
}

func receiverTypeName(recv *ast.FieldList) string {
	if recv == nil || len(recv.List) == 0 {
		return ""
	}
	expr := recv.List[0].Type
	if star, ok := expr.(*ast.StarExpr); ok {
		expr = star.X
	}
	if ident, ok := expr.(*ast.Ident); ok {
		return ident.Name
	}
	return ""
}

